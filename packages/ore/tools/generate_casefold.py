"""Generate from https://www.unicode.org/Public/16.0.0/ucd/CaseFolding.txt.
Usage: python3 tools/generate_casefold.py /path/to/CaseFolding.txt
Unicode data license: https://www.unicode.org/license.txt
"""
import hashlib
from pathlib import Path
import sys

source = Path(sys.argv[1]).read_bytes()
assert source.startswith(b"# CaseFolding-16.0.0.txt")
rows = []
for line in source.decode().splitlines():
    fields = line.split("#", 1)[0].strip().split(";")
    if len(fields) >= 3 and fields[1].strip() in ("C", "F"):
        code = int(fields[0], 16)
        mapping = "".join("\\u{" + str.lower(cp) + "}" for cp in fields[2].split())
        rows.append(f'    (0x{code:x}, "{mapping}"),')
header = "// Generated by tools/generate_casefold.py; do not edit.\n"
header += "// Unicode 16.0.0 CaseFolding.txt (C + F, default full, non-Turkic).\n"
header += "// Source: https://www.unicode.org/Public/16.0.0/ucd/CaseFolding.txt\n"
header += "// License: https://www.unicode.org/license.txt\n"
header += f"// SHA-256: {hashlib.sha256(source).hexdigest()}\n"
Path(__file__).resolve().parents[1].joinpath("src/casefold_unicode16.rs").write_text(
    header + "pub(super) const FOLD: &[(u32, &str)] = &[\n" + "\n".join(rows) + "\n];\n"
)
